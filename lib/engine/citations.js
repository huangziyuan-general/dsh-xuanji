/**
 * 查调候用神。
 * @param {string} dayGan 日干（甲…癸）
 * @param {string} season 季节：春/夏/秋/冬
 * @returns {{ found:boolean, xi:string[], ji:string[], why:string }}
 */
export function tiaoHou(dayGan, season) {
    const row = TIAOHOU[dayGan]?.[season];
    if (!row) return { found: false, xi: [], ji: [], why: '' };
    return { found: true, xi: row.xi, ji: row.ji, why: row.why };
}

/** 已收录的经典书目（去重）。 */
export function citationBooks() {
    return [...new Set(CITATIONS.map((c) => c.book))];
}

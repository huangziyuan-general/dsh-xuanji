/**
 * 按主题检索引文。
 * @param {string} topic 模糊匹配（如 '调候' / '格局' / '纲领'）
 * @returns {Array}
 */
export function citeFor(topic) {
    if (!topic) return CITATIONS;
    const t = String(topic);
    return CITATIONS.filter((c) => c.topic.includes(t) || c.book.includes(t) || c.quote.includes(t));
}

